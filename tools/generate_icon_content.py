"""Compile the bilingual, locally stored icon copy. IDs/categories remain stable.

Per icon: arrival messages, short leads ("… zu <Ziel>"), full route sentences and, under "from",
sentences for a start favourite with a given icon (network plan rows). "_network" holds neutral
two-place sentences. Route sentences contain each of {origin}, {target}, {dep} and {arr} exactly once.
"""
from pathlib import Path
import json,re,sys
ROOT=Path(__file__).resolve().parents[1]
TOKENS=['{origin}','{target}','{dep}','{arr}']
def literal(s): return json.dumps(s,ensure_ascii=False).replace('$','\\$')
data=json.loads((ROOT/'content/icon_context.json').read_text())
icons={k:v for k,v in data.items() if not k.startswith('_')}

def texts(entries,kind):
    for lang in ['de','en']:
        values=[e[lang] for e in entries]
        assert len(set(values))==len(values),(kind,lang,'duplicate')
        assert all(v and (kind=='leads' or v==v.strip()) for v in values),(kind,lang)
        if kind=='routes':
            for v in values:
                assert all(v.count(t)==1 for t in TOKENS),(v,'needs each token once')
                assert not re.search(r'\{(?!origin\}|target\}|dep\}|arr\})',v),(v,'unknown token')
    return 'listOf('+', '.join('IconText(%s,%s)'%(literal(e['de']),literal(e['en'])) for e in entries)+')'

lines=['// SPDX-License-Identifier: GPL-3.0-or-later',
       '// Generated by tools/generate_icon_content.py; edit content/icon_context.json.',
       'package dev.ambivalenton.openv.data.model',
       'internal val generatedIconCopy: Map<FavoriteIcon, IconCopy> by lazy { mapOf(']
for key,row in icons.items():
    assert len(row['arrivals']) >= (20 if key=='PLACE' else 10),key
    assert len(row['leads'])>=6,key
    if key!='PLACE': assert len(row.get('routes',[]))>=5,key
    lines.append(f'    FavoriteIcon.{key} to IconCopy(')
    lines.append('        '+texts(row['arrivals'],'arrivals')+',')
    lines.append('        '+texts(row['leads'],'leads')+',')
    lines.append('        routes='+texts(row.get('routes',[]),'routes')+',')
    pairs=row.get('from',{})
    for origin in pairs: assert origin in icons and origin!=key,(key,origin)
    lines.append('        from=mapOf('+', '.join(f'FavoriteIcon.{o} to '+texts(v,'routes') for o,v in pairs.items())+'),')
    lines.append('    ),')
lines.append(') }')
lines.append('internal val generatedNetworkRoutes: List<IconText> by lazy { '+texts(data['_network'],'routes')+' }\n')
out='\n'.join(lines)
target=ROOT/'app/src/main/java/dev/ambivalenton/openv/data/model/GeneratedIconCopy.kt'
if '--check' in sys.argv: assert target.read_text()==out,'Run tools/generate_icon_content.py'
else: target.write_text(out)
routes=sum(len(r.get('routes',[]))+sum(len(v) for v in r.get('from',{}).values()) for r in icons.values())+len(data['_network'])
print(f"{len(icons)} categories; {sum(len(r['arrivals']) for r in icons.values())} arrivals; {sum(len(r['leads']) for r in icons.values())} leads; {routes} route sentences; DE/EN")
