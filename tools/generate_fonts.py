"""Check unmodified, pinned OFL font binaries and generate the offline family catalogue."""
from pathlib import Path
import hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
items=json.loads((ROOT/'localization/fonts.json').read_text())
assert len(items)>=52 and len({i['id'] for i in items})==len(items)
for item in items:
    font=ROOT/'app/src/main/assets'/item['asset'];license=ROOT/'app/src/main/assets'/item['license_asset']
    assert hashlib.sha256(font.read_bytes()).hexdigest()==item['sha256']
    assert font.stat().st_size==item['bytes']
    assert hashlib.sha256(license.read_bytes()).hexdigest()==item['license_sha256']
    assert 'SIL OPEN FONT LICENSE' in license.read_text() and item['license']=='OFL-1.1'
def lit(s):return json.dumps(s,ensure_ascii=False).replace('$','\\$').replace('\ufeff','\\ufeff')
kt='''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/generate_fonts.py; edit localization/fonts.json.
package dev.ambivalenton.openv.data.model

data class AppFontOption(val id:String,val name:String,val descriptionKey:String,val asset:String,val licenseAsset:String,val copyright:String,val variations:String?=null)
val appFonts=listOf(
'''+''.join('    AppFontOption('+','.join(lit(i[k]) for k in ['id','name','description_de','asset','license_asset','copyright'])+','+(lit(i['variation_settings']) if i.get('variation_settings') else 'null')+'),\n' for i in items)+')\n'
catalog=json.loads((ROOT/'localization/en.json').read_text())
for item in items:catalog[item['description_de']]=item['description_en']
doc='# Mitgelieferte Schriften\n\nAlle Dateien werden unverändert mitgeliefert. Keine Laufzeit-Downloads oder Google-Dienste. Die GPL der App ersetzt nicht die OFL-Lizenzen der Schriften. Vollständige Copyright- und Lizenztexte: `app/src/main/assets/font_licenses/`. Herkunft, Commit, SHA-256 und Dateigrößen: `localization/fonts.json`.\n\nAtkinson Hyperlegible Next ist für Erkennbarkeit gestaltet; Andika und Lexend bieten alternative Leseformen. Eine für alle Menschen geeignete Schrift oder eine Behandlung von Leseschwäche wird nicht behauptet. Persönliche Lesbarkeit lässt sich direkt in der App ausprobieren.\n\n| Schrift | Beschreibung | Lizenz | Quelle |\n| --- | --- | --- | --- |\n'+''.join(f"| {i['name']} | {i['description_de']} | OFL-1.1 | [Originaldatei]({i['source_url']}) |\n" for i in items)
outputs={'app/src/main/java/dev/ambivalenton/openv/data/model/AppFonts.kt':kt,'localization/en.json':json.dumps(catalog,ensure_ascii=False,indent=2,sort_keys=True)+'\n','docs/fonts.md':doc}
for rel,text in outputs.items():
    p=ROOT/rel
    if '--check' in sys.argv:assert p.read_text()==text,f'Regenerate {rel}'
    else:p.write_text(text)
print(f'{len(items)} bundled OFL families verified; {sum(i["bytes"] for i in items)} bytes')
