"""Validate the editorial JSON and compile a pure, offline Kotlin catalogue. No network I/O."""
from pathlib import Path
from collections import Counter
import json, re, sys, unicodedata
from datetime import date
ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'app/src/main/java/dev/ambivalenton/openv/data/model/GeneratedJourneyContent.kt'

def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')

def generate():
    data = json.loads((ROOT/'content/journey_content.json').read_text())
    assert data['schemaVersion'] == 1
    entries = data['entries']
    assert len(entries) >= 400
    assert len({e['id'] for e in entries}) == len(entries)
    assert set(e['kind'] for e in entries) == {'FACT', 'THOUGHT', 'HAIKU', 'SATIRE'}
    for language in ('de','en'):
        seen = set()
        for e in entries:
            text = e['text'][language]
            assert text == text.strip() and 5 <= len(text) <= 400, e['id']
            assert not re.search(r'\{\{|TODO|PLACEHOLDER', text), e['id']
            normal = ' '.join(unicodedata.normalize('NFKC', text).casefold().split())
            assert normal not in seen, (language, e['id'])
            seen.add(normal)
            if e['kind'] == 'HAIKU':
                assert len(text.splitlines()) == 3 and all(text.splitlines()), e['id']
            else:
                assert '\n' not in text, e['id']
    for e in entries:
        assert re.fullmatch(r'[a-z]+-[0-9]{3}', e['id']), e['id']
        if e['kind'] == 'FACT':
            assert e['sourceUrl'].startswith('https://')
            date.fromisoformat(e['verifiedOn'])
            assert e['author'] is None
        else:
            assert e['sourceUrl'] is None and e['author'] == 'Öpen-V · eigene Formulierung'
    lines = [
        '// SPDX-FileCopyrightText: 2026 Ambivalenton',
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/generate_journey_content.py; edit content/journey_content.json.',
        'package dev.ambivalenton.openv.data.model', '',
        'internal val generatedJourneyContent: List<JourneyContent> by lazy { listOf('
    ]
    for e in entries:
        source = literal(e['sourceUrl']) if e['sourceUrl'] else 'null'
        author = literal(e['author']) if e['author'] else 'null'
        verified = literal(e['verifiedOn']) if e['verifiedOn'] else 'null'
        lines.append('    JourneyContent(%s, JourneyContentKind.%s, %s, %s, %s, %s, %s),' % (
            literal(e['id']), e['kind'], literal(e['text']['de']), literal(e['text']['en']), source, author, verified))
    lines.append(') }\n')
    text = '\n'.join(lines)
    if '--check' in sys.argv:
        assert TARGET.read_text() == text, 'Run tools/generate_journey_content.py'
    else:
        TARGET.write_text(text)
    print(json.dumps({'entries':len(entries),'categories':dict(Counter(e['kind'] for e in entries)),
        'languages':['de','en'],'unique':True,'haiku_lines':3}, ensure_ascii=False))

if __name__ == '__main__': generate()
